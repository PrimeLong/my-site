/* ИЛЛЮСТРАЦИИ-СХЕМЫ: кругооборот доходов и расходов (глава «ВВП») и балансы банков по шагам
   (глава «Деньги и банки»). Здесь — только числа; рисует src/textbook-diagrams.jsx. */

export const DIAGRAM_KINDS = ['circular', 'balance'];

/* Кругооборот: одна и та же сумма, измеренная в трёх местах. Числа — из разбора главы:
   хлеб за 1000, добавленная стоимость 300 + 400 + 300. */
export function circularFlow(total = 1000) {
  const va = [['фермер', 0.3], ['мельница', 0.4], ['пекарня', 0.3]].map(([who, k]) => [who, Math.round(total * k)]);
  const inc = [['оплата труда', 0.6], ['прибыль', 0.25], ['налоги на производство и амортизация', 0.15]].map(([who, k]) => [who, Math.round(total * k)]);
  return { spending: total, valueAdded: va, incomes: inc };
}

/* Балансы банков: как кредит становится вкладом. База — наличные, которые принесли в банк;
   rr — норма резервов. Каждый шаг — балансы всех банков (активы = пассивы), денежная масса
   (наличные у людей + вклады) и что изменилось. */
const r2 = (x) => Math.round(x * 100) / 100;
export function balanceSteps(base = 1000, rr = 0.1) {
  const loan1 = r2(base * (1 - rr));
  const loan2 = r2(loan1 * (1 - rr));
  const A = (assets, liab) => ({ name: 'Банк А', assets, liab });
  const B = (assets, liab) => ({ name: 'Банк Б', assets, liab });
  return [
    { title: 'Вклад', text: `Анна приносит в банк А ${base} рублей наличными. У банка появились резервы — актив — и обязательство вернуть Анне вклад — пассив. Денежная масса не изменилась: наличные стали вкладом.`,
      banks: [A([['Резервы', base]], [['Вклад Анны', base]])], cash: 0, changed: ['Резервы', 'Вклад Анны'] },
    { title: 'Кредит', text: `Банк А выдаёт Борису кредит ${loan1}: в активах появляется кредит, а в пассивах — новый вклад Бориса, на который зачислены деньги. Денег, которыми можно платить, стало больше — банк создал их записью в балансе.`,
      banks: [A([['Резервы', base], ['Кредит Борису', loan1]], [['Вклад Анны', base], ['Вклад Бориса', loan1]])], cash: 0, changed: ['Кредит Борису', 'Вклад Бориса'] },
    { title: 'Платёж', text: `Борис платит строителю Вере ${loan1}, у неё счёт в банке Б. Вклад Бориса исчезает, у Веры появляется такой же; банк А передаёт банку Б резервы. У банка А осталось ${r2(base - loan1)} резервов — ровно ${Math.round(rr * 100)}% вклада Анны.`,
      banks: [A([['Резервы', r2(base - loan1)], ['Кредит Борису', loan1]], [['Вклад Анны', base]]), B([['Резервы', loan1]], [['Вклад Веры', loan1]])], cash: 0, changed: ['Резервы', 'Вклад Веры'] },
    { title: 'Второй кредит', text: `Банк Б оставляет ${r2(loan1 - loan2)} в резервах и выдаёт Глебу кредит ${loan2} — опять новым вкладом. Цепочка продолжается, каждый круг меньше предыдущего.`,
      banks: [A([['Резервы', r2(base - loan1)], ['Кредит Борису', loan1]], [['Вклад Анны', base]]), B([['Резервы', loan1], ['Кредит Глебу', loan2]], [['Вклад Веры', loan1], ['Вклад Глеба', loan2]])], cash: 0, changed: ['Кредит Глебу', 'Вклад Глеба'] },
    { title: 'Итог', text: `Когда цепочка дойдёт до конца, во всех банках вместе: резервы — все исходные ${base}, вклады — ${base} / ${String(rr).replace('.', ',')} = ${r2(base / rr)}, кредиты — ${r2(base / rr - base)}. Банки создали ${r2(base / rr - base)} новых денег.`,
      banks: [{ name: 'Все банки', assets: [['Резервы', base], ['Кредиты', r2(base / rr - base)]], liab: [['Вклады', r2(base / rr)]] }], cash: 0, changed: ['Кредиты', 'Вклады'] },
  ].map((s, k) => ({ ...s, no: k + 1, money: r2(s.cash + s.banks.reduce((acc, b) => acc + b.liab.reduce((x, [, v]) => x + v, 0), 0)) }));
}
