const esc = (x) => x.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const bare = (x) => (x.startsWith('{') && x.endsWith('}') ? x.slice(1, -1) : x);
// регулярное выражение обозначения: индекс и степень — со скобками или без
function keyRe(key) {
  if (key.startsWith('\\text{')) return new RegExp(esc(key), 'g');
  const m = /^(\\[A-Za-z]+(?: [A-Za-z])?|[A-Za-z]+)(?:_(\{(?:[^{}]|\{[^{}]*\})*\}|[^{}^]))?(?:\^(\{(?:[^{}]|\{[^{}]*\})*\}|[^{}]))?$/.exec(key);
  if (!m) throw new Error(`Не разобрано обозначение ${key}`);
  const [, base, sub, sup] = m;
  let src = esc(base).replace(/\\ /g, '\\s*');
  if (sub) src += `_\\{?${esc(bare(sub))}\\}?`;
  if (sup) src += `\\^\\{?${esc(bare(sup))}\\}?`;
  /* Записи с индексом и степенью ищутся раньше голой буквы и вырезаются, поэтому P после
     P^* и P_s находит только саму цену. Одна буква может стоять вплотную к другой (kY — это
     k·Y), но не внутри команды (\frac); имя из нескольких букв (MC) — целым словом, перед
     ним может стоять только d производной (dTC/dQ). */
  const word = base.length > 1 && !base.startsWith('\\');
  const after = sub || sup ? '(?![A-Za-z0-9])' : word || base.startsWith('\\') ? '(?![A-Za-z])' : '';
  const before = word ? '(?<![A-Za-ce-z\\\\])' : '(?<!\\\\[A-Za-z]*)';
  return new RegExp(`${before}${src}${after}`, 'g');
}
const COMPILED = {};
const compiled = (chapter) => {
  if (!COMPILED[chapter]) {
    const map = SYMBOLS[chapter] || {};
    // длинные записи раньше коротких: MC раньше C, P^* раньше P
    COMPILED[chapter] = Object.keys(map).sort((a, b) => b.length - a.length).map((k) => ({ key: k, re: keyRe(k), text: map[k] }));
  }
  return COMPILED[chapter];
};

/* Какие обозначения главы есть в формуле: [{ key, text }] по порядку первого появления.
   Найденное вырезается, чтобы буква C в MC не засчиталась ещё раз как «потребление». */
export function formulaSymbols(tex, chapter) { return scan(tex, chapter).found; }
// буквы формулы, которым нет пояснения (для теста полноты словаря)
export function unexplained(tex, chapter) {
  const rest = scan(tex, chapter).rest.replace(/\\[A-Za-z]+/g, ' ').replace(/[_^]\{[^{}]*\}|[_^][A-Za-z0-9]/g, ' ');
  return [...new Set(rest.match(/[A-Za-z]/g) || [])];
}
function scan(tex, chapter) {
  if (!tex || !SYMBOLS[chapter]) return { found: [], rest: String(tex || '') };
  let s = String(tex).replace(/\\(?:left|right|Big|big|,|;|!|quad|qquad|displaystyle)/g, (m) => ' '.repeat(m.length))
    .replace(/\\(?:begin|end)\{[a-z*]+\}/g, (m) => ' '.repeat(m.length));
  const found = [];
  const take = ({ key, re, text }) => {
    re.lastIndex = 0;
    let first = -1;
    s = s.replace(re, (m, ...rest) => { const at = rest[rest.length - 2]; if (first < 0) first = at; return ' '.repeat(m.length); });
    if (first >= 0) found.push({ key, text, at: first });
  };
  const list = compiled(chapter);
  // сначала словесные обозначения (\text{АС}), потом текст в формуле стирается — в нём букв-обозначений нет
  list.filter((x) => x.key.startsWith('\\text{')).forEach(take);
  const withText = list.filter((x) => !x.key.startsWith('\\text{') && x.key.includes('\\text{'));
  withText.forEach(take);
  s = s.replace(/\\(?:text|operatorname|mathrm)\{[^{}]*\}/g, (m) => ' '.repeat(m.length));
  list.filter((x) => !x.key.includes('\\text{')).forEach(take);
  return { found: found.sort((a, b) => a.at - b.at).map(({ key, text }) => ({ key, text })), rest: s };
}
// все обозначения в нескольких формулах (шаг урока с несколькими формулами) — без повторов
export function symbolsOf(texList, chapter) {
  const seen = new Set(); const out = [];
  texList.forEach((t) => formulaSymbols(t, chapter).forEach((x) => { if (!seen.has(x.key)) { seen.add(x.key); out.push(x); } }));
  return out;
}
