const MONTHS_GEN = ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня', 'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'];
// «15 октября»; другой год — с годом
export function newsDate(day, today = null) {
  const [y, m, d] = day.split('-').map(Number);
  const sameYear = !today || today.slice(0, 4) === String(y);
  return `${d} ${MONTHS_GEN[m - 1]}${sameYear ? '' : ` ${y}`}`;
}

/* Прочитанные выпуски — на устройстве (ems-news-seen: id → когда открыли). Новый ученик не видит
   прошлых выпусков как «новых»: всё, что вышло раньше его первого дня, считается прочитанным. */
const SEEN_KEY = 'ems-news-seen';
export function readNewsSeen() {
  try { const v = JSON.parse(localStorage.getItem(SEEN_KEY) || '{}'); return v && typeof v === 'object' ? v : {}; } catch { return {}; }
}
export function markNewsSeen(ids, now = Date.now()) {
  const seen = readNewsSeen();
  ids.forEach((id) => { if (!seen[id]) seen[id] = now; });
  try { localStorage.setItem(SEEN_KEY, JSON.stringify(seen)); } catch { /* приватный режим */ }
  return seen;
}
// непрочитанные выпуски: вышли не раньше первого дня ученика (since) и ещё не открыты
export const unreadNews = (seen, since = null) => NEWS.filter((n) => !seen[n.id] && (!since || n.date >= since));
