const MONTHS_GEN = ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня', 'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'];
// «15 октября»; другой год — с годом
export function newsDate(day, today = null) {
  const [y, m, d] = day.split('-').map(Number);
  const sameYear = !today || today.slice(0, 4) === String(y);
  return `${d} ${MONTHS_GEN[m - 1]}${sameYear ? '' : ` ${y}`}`;
}

/* Первый день ученика: регистрация или самое раннее занятие; ещё ничего нет — сегодня (он только
   пришёл). Выпуск — новость для ученика, только если вышел ПОСЛЕ этого дня: тому, кто только зашёл,
   прошлое обновление не новость — для него новое всё. */
export function learnerSince(learn, now = Date.now()) {
  const l = learn || {};
  const days = [...Object.keys(l.done || {}), ...Object.keys(l.xp || {})].sort();
  const reg = l.profile && l.profile.at ? dayOf(l.profile.at) : null;
  return [days[0], reg].filter(Boolean).sort()[0] || dayOf(now);
}
export const newsForLearner = (n, since) => !since || n.date > since;

/* Прочитанные выпуски — на устройстве (ems-news-seen: id → когда открыли). Новый ученик не видит
   прошлых выпусков как «новых»: всё, что вышло до его первого дня включительно, — не новость. */
const SEEN_KEY = 'ems-news-seen';
export function readNewsSeen() {
  try { const v = JSON.parse(localStorage.getItem(SEEN_KEY) || '{}'); return v && typeof v === 'object' ? v : {}; } catch { return {}; }
}
export function markNewsSeen(ids, now = Date.now()) {
  const seen = readNewsSeen();
  ids.forEach((id) => { if (!seen[id]) seen[id] = now; });
  try { localStorage.setItem(SEEN_KEY, JSON.stringify(seen)); } catch { /* приватный режим */ }
  return seen;
}
// непрочитанные выпуски: вышли после первого дня ученика (since) и ещё не открыты
export const unreadNews = (seen, since = null) => NEWS.filter((n) => !seen[n.id] && newsForLearner(n, since));

/* Лента по дням (экран «Новости»): свежий день сверху; в дне сначала выпуск Инфляции, потом записи
   друзей — свежие выше. События одного друга за день склеены в одну запись. events — лента друзей
   из friendFeed (src/learn/friends.js): уже свежими первыми. */
export function feedDays(news, events = []) {
  const days = new Map();
  const at = (d) => { if (!days.has(d)) days.set(d, { day: d, issues: [], friends: [] }); return days.get(d); };
  news.forEach((n) => at(n.date).issues.push(n));
  events.forEach((e) => {
    const g = at(dayOf(e.at)).friends;
    const p = g.find((x) => x.login === e.login);
    if (p) p.evs.push(e); else g.push({ login: e.login, name: e.name, wear: e.wear, evs: [e] });
  });
  return [...days.values()].sort((a, b) => (a.day < b.day ? 1 : -1));
}
