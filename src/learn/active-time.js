/* ВРЕМЯ УРОКА — только когда ученик на месте (docs/mechanics.md, «Время урока»). Считаем
   секунды, пока вкладка видна и за последнюю минуту было касание, нажатие клавиши или прокрутка.
   Открыл урок, выключил телефон и доделал дома — пауза не попадёт ни в «Время» на итогах, ни в
   минуты цели дня. Часы — чистые функции над объектом { ms, last, act }: тики раз в секунду и
   события ученика двигают их вперёд. Модуль чистый, его читают тесты. */
export const IDLE_MS = 60000; // без касаний дольше минуты — ученика нет на месте
export const TICK_CAP = 5000; // один тик не добавляет больше пяти секунд: спящая вкладка не «догоняет»

// новые часы: start — сейчас, base — уже набранное (продолжение прерванного урока)
export const activeClock = (start, base = 0) => ({ ms: Math.max(0, base), last: start, act: start });
// тик: прибавить время с прошлого тика, если вкладка видна и ученик недавно что-то делал
export function tickClock(c, now, visible = true) {
  const gap = Math.max(0, now - c.last);
  const here = visible && now - c.act <= IDLE_MS;
  return { ...c, ms: c.ms + (here ? Math.min(gap, TICK_CAP) : 0), last: now };
}
// действие ученика: досчитать до сейчас (по прежней отметке активности) и отметить активность
export const actClock = (c, now, visible = true) => ({ ...tickClock(c, now, visible), act: now });
