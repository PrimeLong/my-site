/* Видимое и подсвеченное на шаге k: появившееся раньше остаётся (если не убрано), подсвечено новое
   или то, что в focus; «новое» — для анимации появления. */
export function stepView(g, k) {
  const shown = new Set();
  let added = [];
  for (let i = 0; i <= k && i < g.steps.length; i += 1) {
    const s = g.steps[i];
    (s.hide || []).forEach((id) => shown.delete(id));
    added = (s.add || []).filter((id) => !shown.has(id));
    (s.add || []).forEach((id) => shown.add(id));
  }
  const s = g.steps[Math.min(k, g.steps.length - 1)];
  const focus = new Set(s.focus || s.add || []);
  return { shown, focus, added: new Set(added), values: s.values || {}, marks: s.marks || [], text: s.text };
}
