/* Типографика русского текста (docs/world.md, «Правила», п. 12): неразрывный пробел после коротких предлогов и
   союзов — «в», «к», «с», «о», «у», «и», «а», «на», «по», «за», «от», «до», «из», «не» — и перед тире, чтобы
   короткое слово не висело в конце строки, а тире не начинало новую. Без lookbehind в регулярке: его нет
   в Safari старше 16.4. Чистая функция — её зовут рендер учебника и урока (Inline в src/textbook.jsx) и
   заголовки дизайн-системы (Heading в src/ds.jsx). */
export const NBSP = ' ';
const SHORT = 'в|к|с|о|у|и|а|на|по|за|от|до|из|не';
// короткое слово целиком: перед ним начало строки, пробел, неразрывный пробел или открывающая скобка/кавычка
const AFTER_SHORT = new RegExp(`(^|[\\s(«„"'\\u00a0])(${SHORT})[ \\t]+(?=\\S)`, 'gi');
export function typo(text) {
  if (typeof text !== 'string' || !text) return text;
  let s = text;
  // «и в доме»: совпадения идут подряд, а пробел перед вторым словом уже съеден первым — повторяем, пока меняется
  for (let k = 0; k < 4; k += 1) {
    const next = s.replace(AFTER_SHORT, (m, pre, word) => `${pre}${word}${NBSP}`);
    if (next === s) break;
    s = next;
  }
  // перед тире — неразрывный пробел: «цена — 20 кр.» не начнёт строку с тире
  return s.replace(/[ \t]+—/g, `${NBSP}—`);
}
