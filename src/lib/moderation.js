/* МОДЕРАЦИЯ ТЕКСТА: имена, логины и комментарии к сообщениям об ошибках. Грубые слова не
   проходят ни при регистрации, ни в «Сообщить об ошибке» — на сервере (api/account.js,
   api/reports.js) и заранее на экране, чтобы человек сразу видел, что исправить.
   Ищем корни мата с учётом латинских «двойников» (pizda, xyй), растянутых букв (бляяя) и
   разделителей (х.у.й). Корни подобраны так, чтобы обычные слова не задевать: «небо»,
   «хлеба», «колебание», «команда», «хулиган», «бляха», «педикюр», «оскорблять», «Херсон»,
   «потребление», «сукно» проходят (тест — src/lib/__tests__/moderation.test.js). */
const LOOK = { a: 'а', b: 'б', c: 'с', e: 'е', h: 'н', k: 'к', m: 'м', o: 'о', p: 'р', t: 'т', x: 'х', y: 'у', u: 'у', '0': 'о', '3': 'з', '@': 'а', '6': 'б', 'ё': 'е' };
// латинская транслитерация целиком (pizdec, blyat, suka) — отдельно, до замены двойников
const TRANSLIT = [['shch', 'щ'], ['sch', 'щ'], ['zh', 'ж'], ['ch', 'ч'], ['sh', 'ш'], ['ya', 'я'], ['yo', 'е'], ['ye', 'е'], ['yu', 'ю'], ['kh', 'х'],
  ['a', 'а'], ['b', 'б'], ['v', 'в'], ['g', 'г'], ['d', 'д'], ['e', 'е'], ['z', 'з'], ['i', 'и'], ['j', 'й'], ['k', 'к'], ['l', 'л'], ['m', 'м'], ['n', 'н'],
  ['o', 'о'], ['p', 'п'], ['r', 'р'], ['s', 'с'], ['t', 'т'], ['u', 'у'], ['f', 'ф'], ['h', 'х'], ['c', 'к'], ['y', 'ы'], ['x', 'кс'], ['w', 'в'], ['q', 'к']];
const B = '(?:^|[^а-я])';
const ROOTS = [
  `х[уy]+[йеёияю]`, // хуй, хуе-, хуя- (но не «хулиган», «худо», «хуже»)
  `п[иеё]+зд`, `п[ие]+з[дж]ец`,
  // корень на «-еб-» — только с начала слова или после приставки: «небо», «хлеба», «колебание», «погребла» проходят
  `${B}(?:за|от|у|вы|на|по|раз|рас|при|до|съ|въ|об|пере|под|про)?[её]б(?:[ауыилнтщ]|ать|ёт|ет)`, `долбо[её]б`,
  `${B}бля+(?:[дть]|$|[^а-я])`, `${B}бляд`, `${B}блять`, // но не «бляха», «оскорблять»
  `пид[оа]р`, `пидр`, `педик(?!юр)`, `мудак`, `мудил`, `г[ао]ндон`, `шлюх`, `залуп`, `${B}манд[аую](?:[^а-я]|$)`, `${B}сук[аи](?:[^а-я]|$)`, `дерьм`, `говн[оаюе]`,
  `${B}у[её]б`, `въ[её]б`, `${B}хер(?:ов|ня|н)`,
];
const LATIN = ['fuck', 'shit', 'bitch', 'cunt', 'asshole', 'motherf', 'nigg', 'faggot', 'whore', 'slut'];
const RU_RE = new RegExp(ROOTS.join('|'));

const squeeze = (s) => s.replace(/(.)\1{2,}/g, '$1$1');
function variants(text) {
  const low = String(text || '').toLowerCase().replace(/ё/g, 'е');
  // буквы через точки, пробелы и звёздочки: «х.у.й», «х у й» — склеиваем одиночные буквы
  const glued = low.replace(/(?:^|\s)((?:[a-zа-я][\s.*_-]){2,}[a-zа-я])(?=\s|$)/g, (m) => m.replace(/[\s.*_-]/g, ''));
  const look = (s) => Array.from(s).map((ch) => LOOK[ch] || ch).join('');
  const translit = (s) => { let out = s; TRANSLIT.forEach(([a, b]) => { out = out.split(a).join(b); }); return out; };
  return [low, glued, look(low), look(glued), translit(low), translit(glued)].map(squeeze);
}
// есть ли в тексте грубые слова
export function isRude(text) {
  if (!text) return false;
  const vs = variants(text);
  if (vs.some((v) => RU_RE.test(` ${v} `))) return true;
  const lat = String(text).toLowerCase().replace(/[^a-z]/g, '');
  return LATIN.some((w) => lat.includes(w));
}
