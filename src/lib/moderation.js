/* МОДЕРАЦИЯ ТЕКСТА: имена, логины и комментарии к сообщениям об ошибках. Грубые слова не
   проходят ни при регистрации, ни в «Сообщить об ошибке» — на сервере (api/account.js,
   api/reports.js) и заранее на экране, чтобы человек сразу видел, что исправить.

   Алфавиты не смешиваем. Каждое слово проверяется в своём алфавите:
   • слово только из латиницы (логины, транслит) — по латинским корням: pizdec, blyat, fuck;
     кириллические корни к нему не прикладываем — иначе glebakov читался бы как «гл-ебак-ов»,
     а ebay и hernandez — как мат;
   • слово, где есть кириллица, — по кириллическим корням; латинские буквы-двойники внутри
     такого слова (xyй, pизда) заменяются на кириллицу, а оставшиеся латинские буквы — часть
     слова, не граница.
   Растянутые буквы (бляяя) сжимаются, разделённые (х.у.й, x y u) склеиваются. Список имён,
   фамилий и логинов, которые обязаны проходить, — в src/lib/__tests__/moderation.test.js. */

// латинские двойники и цифры, похожие на кириллические буквы, — только внутри «кириллического» слова
const LOOK = { a: 'а', b: 'б', c: 'с', e: 'е', h: 'н', k: 'к', m: 'м', o: 'о', p: 'р', t: 'т', x: 'х', y: 'у', u: 'у', '0': 'о', '3': 'з', '@': 'а', '6': 'б' };
// цифры и знаки, которыми заменяют латинские буквы: p1zda, $uka
const LATIN_LOOK = { '0': 'o', '1': 'i', '3': 'e', '4': 'a', '@': 'a', '$': 's' };

const CY = 'а-яё';
// граница слова: начало, конец или не буква (ни кириллическая, ни латинская)
const B = `(?:^|[^${CY}a-z])`;
const E = `(?:$|[^${CY}a-z])`;
const RU_ROOTS = [
  `х[у]+[йеёияю]`, // хуй, хуе-, хуя- (но не «хулиган», «худо», «хуже», «Хуан»)
  `п[иеё]+зд`, `п[ие]+з[дж]ец`,
  // корень на «-еб-» — только с начала слова или после приставки: «небо», «хлеба», «колебание», «погребла» проходят
  `${B}(?:за|от|у|вы|на|по|раз|рас|при|до|съ|въ|об|пере|под|про)?[её]б(?:[ауыилнтщ]|ать|ёт|ет)`, `долбо[её]б`,
  `${B}бля+(?:[дть]|${E})`, // но не «бляха», «оскорблять»
  `пид[оа]р`, `пидр`, `педик(?!юр)`, `${B}мудак`, `мудил`, `г[ао]ндон`, `шлюх`, `залуп`, `${B}манд[аую]${E}`, `${B}сук[аи]${E}`, `дерьм`, `говн[оаюе]`,
  `${B}у[её]б`, `въ[её]б`, `${B}хер(?:ов|ня|н)`,
];
const LA = 'a-z';
const LB = `(?:^|[^${LA}])`;
const LE = `(?:$|[^${LA}])`;
const LATIN_ROOTS = [
  // русский мат латиницей
  `p[ie]+zd`, `${LB}bl+y+a+(?:d|t|${LE})`, `${LB}xy[uiyj](?:${LE}|n)`, `${LB}(?:x|kh|h)u[yj]+${LE}`, `${LB}na(?:x|kh|h)u[yji]`, `${LB}(?:x|kh)uy?e(?:v|s|t|l)`,
  `${LB}(?:za|ot|vy|na|po|raz|pri|do|pere|pro|pod|u)?(?:y?e|yo|jo)b(?:at|al|an[yinu]|ut|ish|et|en|ok|lo|li|la|uch)`, `dolbo(?:y?e|yo)b`,
  `pid[oa]r`, `pidr`, `${LB}mudak`, `mudil`, `g[ao]nd[oa]n`, `shl[y]?uh`, `zalup`, `${LB}suk[ai]${LE}`, `${LB}govn[oa]`, `${LB}dermo${LE}`,
  // английские
  `fuck`, `${LB}shit(?:${LE}|ty|s|head|hole)`, `${LB}bitch(?:${LE}|es|y)`, `${LB}cunt`, `asshole`, `motherf`, `${LB}nigg(?:a|er)`, `faggot`, `whore`, `${LB}slut(?:${LE}|ty)`,
];
const RU_RE = new RegExp(RU_ROOTS.join('|'));
const LATIN_RE = new RegExp(LATIN_ROOTS.join('|'));

const squeeze = (s) => s.replace(/(.)\1{2,}/g, '$1$1');
const HAS_CY = new RegExp(`[${CY}]`);
const HAS_LA = /[a-z]/;
// буквы через точки, пробелы и звёздочки: «х.у.й», «x y u» — склеиваем одиночные буквы
const glue = (s) => s.replace(new RegExp(`(?:^|\\s)((?:[a-z${CY}][\\s.*_-]){2,}[a-z${CY}])(?=\\s|$)`, 'g'), (m) => ` ${m.replace(/[\s.*_-]/g, '')}`);
// слова — куски из букв и цифр-двойников; всё остальное — разделители
const words = (s) => s.split(new RegExp(`[^a-z${CY}0-9@$]+`)).filter(Boolean);

function checkWord(w) {
  if (HAS_CY.test(w)) {
    // кириллическое слово: двойники — в кириллицу (u похожа и на «у», и на «и»), остальная латиница остаётся буквами
    return ['у', 'и'].some((u) => {
      const ru = Array.from(w).map((ch) => (ch === 'u' ? u : LOOK[ch] || ch)).join('');
      return RU_RE.test(` ${squeeze(ru)} `);
    });
  }
  if (HAS_LA.test(w)) {
    // цифры по краям (suka777) — не часть слова; цифры внутри — часть слова, а не граница (gleb73blow)
    const core = w.replace(/^[0-9]+|[0-9]+$/g, '');
    const la = Array.from(core).map((ch) => LATIN_LOOK[ch] || (/[0-9]/.test(ch) ? 'q' : ch)).join('');
    return LATIN_RE.test(` ${squeeze(la)} `);
  }
  return false;
}

// есть ли в тексте грубые слова
export function isRude(text) {
  if (!text) return false;
  const low = String(text).toLowerCase().replace(/ё/g, 'е');
  return [low, glue(low)].some((v) => words(v).some(checkWord));
}
