// Типографика: неразрывный пробел после коротких предлогов и союзов и перед тире (docs/world.md, «Правила»)
import { describe, it, expect } from 'vitest';
import { typo, NBSP } from '../typo.js';

const show = (s) => s.replaceAll(NBSP, '~');

describe('неразрывные пробелы', () => {
  it('после однобуквенных и двухбуквенных предлогов и союзов', () => {
    expect(show(typo('Кофе в кофейне и на улице'))).toBe('Кофе в~кофейне и~на~улице');
    expect(show(typo('В кофейне у метро'))).toBe('В~кофейне у~метро');
    ['в', 'к', 'с', 'о', 'у', 'и', 'а', 'на', 'по', 'за', 'от', 'до', 'из', 'не'].forEach((w) => {
      expect(show(typo(`слово ${w} слово`)), w).toBe(`слово ${w}~слово`);
    });
  });
  it('подряд идущие короткие слова — все; внутри слов и после длинных слов — нет', () => {
    expect(show(typo('и в доме, а не в саду'))).toBe('и~в~доме, а~не~в~саду');
    expect(show(typo('вода собака'))).toBe('вода собака');
    expect(show(typo('вино нагрето'))).toBe('вино нагрето');
    expect(show(typo('(в скобках) «и кавычках»'))).toBe('(в~скобках) «и~кавычках»');
  });
  it('перед тире — неразрывный пробел, после — обычный', () => {
    expect(show(typo('Цена — 20 кр.'))).toBe('Цена~— 20 кр.');
    expect(show(typo('спрос — это желание, а не нужда'))).toBe('спрос~— это желание, а~не~нужда');
  });
  it('пустое и не строка — как есть; повторный вызов ничего не меняет', () => {
    expect(typo('')).toBe('');
    expect(typo(null)).toBe(null);
    expect(typo(5)).toBe(5);
    const once = typo('Маша и Тимур в кофейне — как всегда');
    expect(typo(once)).toBe(once);
  });
});
