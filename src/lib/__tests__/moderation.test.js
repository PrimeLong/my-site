import { describe, it, expect } from 'vitest';
import { isRude } from '../moderation.js';

describe('модерация: грубые слова в именах и сообщениях', () => {
  it('ловит мат, транслит, латинских двойников, растянутые и разделённые буквы', () => {
    ['Это пиздец блять какая нахуй МАША', 'Pidoras', 'бляяять', 'х.у.й', 'xyй', 'pizdec', 'сука', 'ёбаный', 'заебали', 'долбоёб', 'fuck this', 'мудак', 'гондон', 'херня']
      .forEach((t) => expect(isRude(t), t).toBe(true));
  });
  it('обычные слова и жалобы проходят', () => {
    ['Тут нужен калькулятор, а его нет', 'Privet', 'небо', 'хлеба', 'колебание', 'команда', 'хулиган', 'бляха ремня', 'педикюр', 'оскорблять', 'Херсон',
      'потребление', 'сукно', 'погребла', 'художник', 'хуже', 'Маша', 'tester', 'Анна', 'ребята', 'учебник', 'судебный', 'колебнуться', 'дебет', 'Себастьян', 'гребля', 'Сукачёв', 'Хуан']
      .forEach((t) => expect(isRude(t), t).toBe(false));
  });
});
