import { describe, it, expect } from 'vitest';
import { plural } from '../plural.js';

describe('склонение по числу — одна функция на всё приложение', () => {
  it('1 урок, 2 урока, 5 уроков, 11 уроков, 21 урок, 104 урока', () => {
    const f = (n) => plural(n, 'урок', 'урока', 'уроков');
    expect([1, 2, 5, 11, 12, 14, 21, 22, 25, 104, 111, 0].map(f)).toEqual(['урок', 'урока', 'уроков', 'уроков', 'уроков', 'уроков', 'урок', 'урока', 'уроков', 'урока', 'уроков', 'уроков']);
  });
});
