#!/usr/bin/env node
/* Тексты для озвучки книг полки (src/learn/shelf.js): по файлу на книгу в папке books/ и инструкция
   books/README.md с таблицей — какой файл записи ждёт каждая книга и какие уже записаны. Готовую запись
   кладут в public/books/<id>.mp3; после сборки кнопка «Слушать книгу» играет её. В тексте для озвучки
   нет пропусков «[…]» — на них сервисы долго молчат.

   Запуск: npm run books:export */
import { writeFile, mkdir } from 'node:fs/promises';
import { BOOKS, speechScript, speechSeconds } from '../src/learn/shelf.js';
import { listBookAudio } from './voice-files-plugin.js';

const out = new URL('../books/', import.meta.url);
const recorded = new Set(listBookAudio());
const num = (n) => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
const mins = (s) => `${Math.max(1, Math.round(s / 60))} мин`;

await mkdir(out, { recursive: true });
for (const b of BOOKS) {
  const text = speechScript(b);
  const head = [
    `${b.author} — «${b.title}» (${b.year})`,
    `Файл записи: ${b.id}.mp3 — положить в папку public/books/`,
    `Знаков: ${num(text.length)} · звучит примерно ${mins(speechSeconds(b))} · записано: ${recorded.has(b.id) ? 'да ✓' : 'нет'}`,
    `Отрывков: ${b.passages.length} — ${b.passages.map((p) => p.title).join(', ')}.`,
    '',
    '— текст для озвучки (копировать всё, что ниже этой строки) —',
    '',
  ];
  await writeFile(new URL(`${b.id}.txt`, out), `${head.join("\n")}\n${text}\n`);
}

const rows = BOOKS.map((b) => `| ${b.author}, «${b.short}» | [${b.id}.txt](${b.id}.txt) | \`${b.id}.mp3\` | ${num(speechScript(b).length)} | ≈ ${mins(speechSeconds(b))} | ${recorded.has(b.id) ? '✓' : '—'} |`);
const total = BOOKS.reduce((a, b) => a + speechScript(b).length, 0);
const readme = `# Озвучка книг полки

На книжной полке профиля ${BOOKS.length} книг, и у каждой **одна запись** — вся книга подряд, около
${num(total)} знаков на все книги. Пока записи нет, книгу по абзацам читает голос браузера. Когда запись
появляется, кнопка «Слушать книгу» играет её: с перемоткой, скоростью, «слушать с этого отрывка» и
подсветкой отрывка, который звучит сейчас.

Этот файл и тексты книг пишет команда \`npm run books:export\` — править их руками не нужно.

## Как озвучить

1. Откройте FreeTTS (или другой сервис) и выберите **один русский голос** для всех книг — спокойный,
   «дикторский», темп обычный.
2. Откройте текст книги из таблицы ниже и скопируйте всё, что ниже строки «— текст для озвучки —».
3. Вставьте текст в сервис, озвучьте и скачайте MP3.
   Если сервис не берёт столько текста за раз — озвучьте по частям (удобно резать по названиям
   отрывков) и склейте части в один MP3, например в бесплатной программе Audacity: «Файл → Импорт →
   Аудио» для каждой части, перетащить их друг за другом на одну дорожку, «Файл → Экспорт → MP3».
4. Назовите файл как в столбце «Файл записи» (например, \`smith-wealth.mp3\`) — маленькими буквами,
   ровно как в таблице.
5. Положите файлы в папку \`public/books/\`. На GitHub: откройте \`public/books\` →
   **Add file → Upload files**, перетащите MP3 и нажмите **Commit changes**.
6. **Выровняйте громкость:** \`npm run voice:normalize\` (нужен ffmpeg) — речь −16 LUFS, пик не выше
   −1,5 dBTP, моно, 56 кбит/с, без обложки; \`npm run voice:normalize -- --check\` только проверяет.
   Без этого шага книга играет на громкости сервиса (Смит был −14,3 LUFS с перегрузом) и заметно
   громче эфиров «Слушай».
7. Vercel соберёт сайт сам. После сборки книга играет запись — ничего больше перечислять не нужно.

Записывать всё сразу не обязательно: книги без записи по-прежнему прочитает браузер.

## Книги

| Книга | Текст | Файл записи | Знаков | Звучит | Записано |
|---|---|---|---:|---:|:---:|
${rows.join('\n')}

## Полезно знать

- **Без «[…]».** В тексте для озвучки пропуски убраны, чтобы сервис не молчал на них. На экране книги
  пропуски по-прежнему отмечены «[…]».
- **Произношение.** Текст в сервисе можно править: ставить ударения так, как их понимает сервис, писать
  годы и числа словами. Имя файла от этого не меняется.
- **Текст книги поменяли.** Команда \`npm run books:export\` (или просьба к Claude) обновит эту папку.
  Старая запись продолжит играть, но подсветка отрывков может немного разойтись с голосом — книгу
  лучше переозвучить.
- **Размер.** Хватит моно MP3 на 48–64 кбит/с: минута записи — около 0,4 МБ. Записи не скачиваются
  заранее: браузер берёт их по кускам, когда книгу слушают.
- **Лицензия.** Перед публикацией проверьте в условиях сервиса, можно ли выкладывать записи на сайт.
  Под проигрывателем всегда видна подпись «голос синтезирован». Сами тексты — в общественном
  достоянии, перевод — редакции «Инфляции».
`;
await writeFile(new URL('README.md', out), readme);
console.log(`Книг: ${BOOKS.length}, знаков: ${num(total)}, записано: ${BOOKS.filter((b) => recorded.has(b.id)).length}. Папка books/ обновлена.`);
